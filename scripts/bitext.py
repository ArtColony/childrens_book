#!/usr/bin/env python3
"""The text of a bilingual book, from one source: its manuscript table.

    scripts/bitext.py gen books/the-golden-pig    # -> books/the-golden-pig/text.ps
    scripts/bitext.py fit books/the-golden-pig    # check every page fits its bands
    scripts/bitext.py check books/the-golden-pig  # text.ps is up to date (for CI)

The manuscript (02-retelling.md) has a table whose rows start
`| N | English | 한국어 | ...`. `gen` writes text.ps, which defines
/cb-gp-text: an array indexed by page number, each entry [(korean) (english)].
Storyboard and page files `run` it, so a manuscript edit reaches every page
and nothing is typed twice.

`fit` sets every page in the real fonts with cb-lines, at the sizes and
widths the page frame uses, and fails when a page needs more lines than its
band holds, or leaves a widow (one word alone on its last line, in either
language). Standard library only.
"""
import os
import re
import subprocess
import sys
import tempfile

ROW = re.compile(r"^\| (\d+) \|")
# the page frame's type (lib/cb_goldpig.ps, cb-gp-texts)
EN = ("/NewCenturySchlbk-Roman", 19, 500, 4)   # font, size, column width, max lines
KO = ("/NotoSansKR-Regular", 20, 500, 4)


def rows(book):
    out = {}
    with open(os.path.join(book, "02-retelling.md"), encoding="utf-8") as f:
        for line in f:
            m = ROW.match(line)
            if m:
                cells = [c.strip() for c in line.strip().strip("|").split("|")]
                n, en, ko = int(cells[0]), cells[1], cells[2]
                # a row with no Korean describes its page (the back matter)
                # rather than giving its text
                out[n] = (clean(ko), clean(en)) if clean(ko) else ("", "")
    return [out.get(i, ("", "")) for i in range(max(out) + 1)] if out else []


def clean(s):
    s = s.replace("**", "").replace("*", "")
    return re.sub(r"\s+", " ", s).strip()


def psstr(s):
    s = s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
    return "(" + s.replace("\n", "\\n") + ")"


def about(book):
    """The back matter: the ```ko and ```en blocks under '## Back matter'.
    Paragraphs (blank-line separated) are joined with \\n\\n for cb-text."""
    with open(os.path.join(book, "02-retelling.md"), encoding="utf-8") as f:
        md = f.read()
    if "## Back matter" not in md:
        return None
    md = md.split("## Back matter", 1)[1]
    out = {}
    for lang in ("ko", "en"):
        m = re.search(r"```" + lang + r"\n(.*?)```", md, re.S)
        if m:
            paras = [re.sub(r"\s+", " ", p).strip() for p in m.group(1).strip().split("\n\n")]
            out[lang] = "\n\n".join(paras)
    return out.get("ko", ""), out.get("en", "")


def generate(book):
    pages = rows(book)
    lines = [
        "%!PS-Adobe-3.0",
        "% text.ps -- GENERATED by scripts/bitext.py from 02-retelling.md. Do not edit;",
        "% edit the manuscript and run `scripts/bitext.py gen` instead.",
        "/cb-gp-text [",
    ]
    for i, (ko, en) in enumerate(pages):
        lines.append(f"  [ {psstr(ko)}\n    {psstr(en)} ]   % {i}")
    lines.append("] def")
    ab = about(book)
    if ab:
        lines.append("% the back matter; paragraphs are separated by \\n\\n")
        lines.append(f"/cb-gp-about [ {psstr(ab[0])}\n  {psstr(ab[1])} ] def")
    return "\n".join(lines) + "\n"


def fit(book):
    pages = rows(book)
    prog = ["(lib/cb_book.ps) run", "/bad 0 def"]
    for i, (ko, en) in enumerate(pages):
        for (font, size, width, most), text, tag in ((EN, en, "en"), (KO, ko, "ko")):
            if not text:
                continue
            prog.append(
                f"{font} findfont {size} scalefont setfont {psstr(text)} {width} cb-lines "
                f"dup length {most} gt {{ (page {i} {tag}: ) print dup length 3 string cvs print ( lines, over {most}) = /bad bad 1 add def }} if "
                # a widow: more than one line, and the last is a single word
                f"dup length 1 gt {{ dup dup length 1 sub get ( ) search {{ pop pop pop }} {{ (page {i} {tag}: widow: ) print = /bad bad 1 add def }} ifelse }} if pop"
            )
    prog.append("bad 0 eq { (bitext: every page fits) = } { (bitext: pages over their bands) = } ifelse")
    with tempfile.NamedTemporaryFile("w", suffix=".ps", delete=False, encoding="utf-8") as f:
        f.write("\n".join(prog) + "\n")
        path = f.name
    try:
        r = subprocess.run(["pscat", "-e", f"({path}) run"], capture_output=True, text=True)
    finally:
        os.unlink(path)
    out = r.stdout + r.stderr
    print(out, end="")
    return r.returncode == 0 and "every page fits" in out and "warning: font" not in out


def main():
    if len(sys.argv) != 3 or sys.argv[1] not in ("gen", "fit", "check"):
        print(__doc__, file=sys.stderr)
        return 2
    cmd, book = sys.argv[1], sys.argv[2].rstrip("/")
    target = os.path.join(book, "text.ps")
    if cmd == "gen":
        with open(target, "w", encoding="utf-8") as f:
            f.write(generate(book))
        print(f"bitext: wrote {target}")
        return 0
    if cmd == "check":
        with open(target, encoding="utf-8") as f:
            if f.read() != generate(book):
                print(f"bitext: {target} is stale; run scripts/bitext.py gen {book}", file=sys.stderr)
                return 1
        print(f"bitext: {target} is up to date")
        return 0
    return 0 if fit(book) else 1


if __name__ == "__main__":
    sys.exit(main())
